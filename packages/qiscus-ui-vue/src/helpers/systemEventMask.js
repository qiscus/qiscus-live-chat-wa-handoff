/**
 * Mask agent names inside "agent joined a room / handover" system-event
 * messages.
 *
 * Product decision (Slack C086Y2YD5J9, Alif 2026-07-06): when a tenant enables
 * the "Hide system event agent joined to room" setting
 * (app_additional_config HIDE_SYSTEM_EVENT_AGENT_NAME), every agent name that
 * appears in a room-join / handover system event is replaced with the literal
 * `an agent`. Scope covers ALL join-related events, not just the bot handover.
 *
 * Port of inbox-v2/src/lib/systemEventMask.ts — keep the two in sync. This copy
 * serves the customer widget AND the legacy agent inbox (both render through
 * qiscus-ui-vue Comment.vue / CommentEmail.vue). The name is baked into the SDK
 * comment by the backend, so this masking is UI-only.
 *
 * NOTE: qiscus-ui-vue has no test runner. The RULES below are covered only by
 * inbox-v2/src/__tests__/systemEventMask.test.ts. If you change a regex here,
 * mirror it in the .ts file and update that test, or it will silently drift.
 *
 * Message templates covered (the whole comment message equals one of):
 *   - "<name> joined this conversation"
 *   - "<name> has joined this conversation"
 *   - "This conversation was handed over to <name>"
 *   - "This conversation was handed over to <name> via Bot"
 *   - "<name> handed over this conversation to <name>"       (+ " via Bulk Assignment")
 *   - "Admin handover this conversation to <name>"
 *   - "<name> was added to this conversation by <actor>"     (SDK-native, payload
 *   - "<name> was removed from this conversation by <actor>"  type "assign_agent")
 *   - "<name> was auto-assigned to this conversation by <actor>"  (auto-assign / round-robin)
 *   - "This conversation was marked as resolved by <name>"        (resolve; keeps role labels)
 *   - "This conversation was taken over by <name>"                (takeover_unserved)
 *   - "<name> has taken over this conversation"                   (agent takeover)
 *   - "<name> joined for Whatsapp Call"                           (WA Call join)
 *   - "<name> left this conversation via Leave Room feature"
 *   - "<name> was replaced with <name> in this conversation by <actor>"
 *   - "Several agents have been replaced with <name> in this conversation by <actor>"
 *   - "<name> blocked this customer chat" / "<name> unblocked this customer chat"
 *
 * The added/removed pair is generated by the Qiscus SDK core (not the
 * omnichannel repos) when a participant is added/removed — confirmed from a
 * live get_room_by_id payload.
 */

const AGENT = 'an agent';

// Actors/subjects that are role labels, not personal agent names — keep them
// visible. Used both for the "... by <actor>" slot (a real agent adding another
// agent gets masked, "Admin"/"System"/"Bot" stay) and for the resolve event,
// where the backend bakes a literal "Supervisor"/"Admin" when a role — not a
// named user — resolved the room (qismo-api qiscus_rooms.ex).
const ACTOR_ROLE = /^(admin|system|bot|supervisor)$/i;

// Ordered rules. Each is anchored to the whole message so a free-form name is
// only ever matched in its fixed grammatical slot. The lazy `.+?` for a name
// leaves the optional trailing marker for its capture group so it survives.
const RULES = [
  // "<name>[ has] joined this conversation"
  [/^.+?( has)? joined this conversation$/i, `${AGENT}$1 joined this conversation`],
  // "This conversation was handed over to <name>[ via Bot]"
  [
    /^This conversation was handed over to .+?( via Bot)?$/i,
    `This conversation was handed over to ${AGENT}$1`,
  ],
  // "<name> handed over this conversation to <name>[ via Bulk Assignment]"
  [
    /^.+? handed over this conversation to .+?( via Bulk Assignment)?$/i,
    `${AGENT} handed over this conversation to ${AGENT}$1`,
  ],
  // "Admin handover this conversation to <name>" (literal "Admin" prefix)
  [/^(Admin handover this conversation to ).+$/i, `$1${AGENT}`],
  // "<name> was added to / removed from / auto-assigned to this conversation
  // by <actor>" (SDK-native assign_agent event + omnichannel auto-assign /
  // round-robin, which always writes "by System"). Mask the participant; mask
  // the actor too unless it's a role label like "Admin"/"System"/"Bot".
  [
    /^.+? was (added to|removed from|auto-assigned to) this conversation by (.+)$/i,
    (_m, verb, actor) => `${AGENT} was ${verb} this conversation by ${ACTOR_ROLE.test(actor) ? actor : AGENT}`,
  ],
  // "This conversation was marked as resolved by <name>". The trailing token is
  // the resolver — a personal name (agent/supervisor) gets masked, but the
  // backend's literal role labels ("Admin"/"Supervisor") are kept.
  [
    /^(This conversation was marked as resolved by )(.+)$/i,
    (_m, prefix, resolver) => `${prefix}${ACTOR_ROLE.test(resolver) ? resolver : AGENT}`,
  ],
  // "This conversation was taken over by <name>" (takeover_unserved).
  [/^(This conversation was taken over by ).+$/i, `$1${AGENT}`],
  // "<name> has taken over this conversation" (agent takeover).
  [/^.+? has taken over this conversation$/i, `${AGENT} has taken over this conversation`],
  // "<name> joined for Whatsapp Call" (WA Call join).
  [/^.+? joined for Whatsapp Call$/i, `${AGENT} joined for Whatsapp Call`],
  // "<name> left this conversation via Leave Room feature".
  [
    /^.+? left this conversation via Leave Room feature$/i,
    `${AGENT} left this conversation via Leave Room feature`,
  ],
  // "<name> was replaced with <name> in this conversation by <actor>".
  [
    /^.+? was replaced with .+? in this conversation by (.+)$/i,
    (_m, actor) => `${AGENT} was replaced with ${AGENT} in this conversation by ${ACTOR_ROLE.test(actor) ? actor : AGENT}`,
  ],
  // "Several agents have been replaced with <name> in this conversation by <actor>".
  [
    /^(Several agents have been replaced with ).+? in this conversation by (.+)$/i,
    (_m, prefix, actor) => `${prefix}${AGENT} in this conversation by ${ACTOR_ROLE.test(actor) ? actor : AGENT}`,
  ],
  // "<name> blocked / unblocked this customer chat" (admin/agent block action;
  // qismo-api customer_controller pushes this into the room). The name leads.
  [
    /^.+? (unblocked|blocked) this customer chat$/i,
    (_m, verb) => `${AGENT} ${verb} this customer chat`,
  ],
];

// Some render surfaces prepend a "HH:MM:SS - " timestamp to the comment text.
const TIMESTAMP_PREFIX = /^(\d{1,2}:\d{2}(?::\d{2})?\s*-\s*)/;

/**
 * Returns `message` with any agent name in a join/handover system event
 * replaced by `an agent`. Non-matching messages are returned unchanged.
 */
function maskSystemEventAgentName(message) {
  if (!message || typeof message !== 'string') return message;

  const tsMatch = message.match(TIMESTAMP_PREFIX);
  const prefix = tsMatch ? tsMatch[1] : '';
  const body = prefix ? message.slice(prefix.length) : message;

  for (let i = 0; i < RULES.length; i += 1) {
    const [pattern, replacement] = RULES[i];
    if (pattern.test(body)) {
      return prefix + body.replace(pattern, replacement);
    }
  }
  return message;
}

/**
 * Escape the five HTML-significant characters so a plain-text system event can
 * be handed to `v-html` without becoming an injection vector. Mirrors the
 * escape step in inbox-v2 SystemMessage.vue / TextMessage.vue.
 */
function escapeSystemEventHtml(text) {
  if (text == null) return '';
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Turn http(s) URLs inside an already-escaped system-event string into
 * clickable anchors (opens in a new tab). Client feedback (SATU Dental via
 * CAPI): agents receive system events carrying a link and want to open it in
 * one click instead of copy-pasting. Plain URLs only — no markdown labels.
 *
 * IMPORTANT: pass ESCAPED text in. The regex only matches `https?://…`, so the
 * anchor href/text is safe, but any surrounding text must already be escaped.
 * Port of the linkify in inbox-v2 SystemMessage.vue — keep the two in sync.
 */
function linkifySystemEvent(escapedText) {
  const urlRegex = /(https?:\/\/[^\s<]+)/g;
  return String(escapedText).replace(
    urlRegex,
    '<a href="$1" target="_blank" rel="noopener noreferrer">$1</a>',
  );
}

/**
 * Convenience: escape then linkify a raw system-event string in one call.
 * Returns HTML safe to bind with `v-html`.
 */
function renderSystemEventHtml(text) {
  return linkifySystemEvent(escapeSystemEventHtml(text));
}

export {
  maskSystemEventAgentName,
  escapeSystemEventHtml,
  linkifySystemEvent,
  renderSystemEventHtml,
};
